function qsValue(param) {
  if (param.required) return `{{parameters.${param.name}}}`;
  if (preservesFalsyValue(param)) {
    return `{{if(parameters.${param.name} != null, parameters.${param.name}, undefined)}}`;
  }
  return `{{ifempty(parameters.${param.name}, undefined)}}`;
}

function bodyValue(param) {
  if (param.required) return `{{parameters.${param.name}}}`;
  if (preservesFalsyValue(param)) {
    return `{{if(parameters.${param.name} != null, parameters.${param.name}, undefined)}}`;
  }
  return `{{ifempty(parameters.${param.name}, undefined)}}`;
}

function qsFromParams(params) {
  return Object.fromEntries(params.map((param) => [param.apiName || param.name, qsValue(param)]));
}

function bodyFromParams(params) {
  return Object.fromEntries(params.map((param) => [param.apiName || param.name, bodyValue(param)]));
}

function commonSearchQs(params) {
  return {
    ...qsFromParams(params),
    ResultsPerPage: "{{if(parameters.limit < 100, parameters.limit, 100)}}",
    Page: "{{pagination.page}}"
  };
}

function writeRpc(rpc) {
  const dir = `rpcs/${rpc.name}`;
  writeJson(`${dir}/metadata.json`, {
    name: rpc.name,
    label: rpc.label,
    description: rpc.description
  });
  writeJson(`${dir}/parameters.imljson`, rpc.parameters || []);
  writeJson(`${dir}/api.imljson`, rpc.api);
}

function writeModule(module) {
  const dir = `modules/${module.dir}`;
  writeJson(`${dir}/metadata.json`, {
    name: module.name,
    label: module.label,
    description: module.description,
    connection: "api-key",
    type: module.kind,
    typeId: module.typeId
  });
  writeJson(`${dir}/api.imljson`, module.api);
  writeJson(`${dir}/expect.imljson`, module.expect || []);
  writeJson(`${dir}/interface.imljson`, module.interface || [anyField("body", "Body")]);
  writeJson(`${dir}/samples.imljson`, module.sample || { ok: true });
}

function searchModule({
  dir,
  name,
  label,
  description,
  url,
  params = [],
  collection,
  itemInterface,
  sample
}) {
  const api = {
    url,
    method: "GET",
    qs: commonSearchQs(params),
    response: {
      iterate: `{{body.${collection}}}`,
      output: "{{item}}",
      limit: "{{parameters.limit}}"
    },
    pagination: {
      condition: "{{body.Records.Page < body.Records.Pages}}",
      qs: {
        Page: "{{pagination.page}}"
      }
    }
  };

  return {
    dir,
    name,
    label,
    description,
    kind: "search",
    typeId: 9,
    api,
    expect: [...params, limitParam],
    interface: itemInterface,
    sample
  };
}

